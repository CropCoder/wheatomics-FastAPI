"""Resolve a BLAST database / subject id to a JBrowse dataset + refseq.

Why the indirection
-------------------
A BLAST subject id is not directly usable as a JBrowse ``loc``. The same
assembly is spelled differently on each side:

    BLAST .fai seqid        Chr1A_AK58      (assembly suffix)
    annotation header loc=  Chr1A           (gene table style)
    JBrowse refseq          chr1A           (seq/refSeqs.json)

and some assemblies use yet another convention (e.g. Sumai3's
``Chr1A_Sumai3``). Name heuristics alone matched only 9 of 203 genome
databases in the 2026-11 audit, so the mapping is precomputed:

    scripts/build_blast_jbrowse_map.py   ->   app/services/data/blast_jbrowse_map.json

The build script joins, per genome assembly base name:
  * BLAST ``<base>.genome.fai``      (seqid + length)
  * JBrowse ``<dataset>/seq/refSeqs.json``  (refseq + length)
  * ``genome_registry`` rows         (base -> jbrowse_dataset, chromosome count)

matching by **chromosome length first** (same assembly => identical lengths)
and by normalised name second. A database whose lengths do not line up is
flagged ``assembly_match: false`` and gets no link at all — that is the guard
against e.g. ``HH_Morex`` (BLAST Morex 516 Mb chr1H) vs the scaffold-level
``Morex`` JBrowse dataset (first refseq 680 kb).

This module only reads that JSON (mtime-cached) and answers two questions:

    jbrowse_meta(db)            -> is there a browser for this database?
    resolve_tokens(db, tokens)  -> which refseq do these hit ids map to?
"""

from __future__ import annotations

import json
import os
import re
import urllib.parse
from pathlib import Path
from typing import Iterable, Optional

from app.core.config import settings

#: Generated by scripts/build_blast_jbrowse_map.py (documented in README).
MAP_FILE = Path(__file__).resolve().parent / "data" / "blast_jbrowse_map.json"

#: Cap on tokens accepted by one resolution call (a result table can have
#: 50k rows; the frontend only sends distinct ids, this is the hard stop).
MAX_TOKENS = 500

_CHROM_RE = re.compile(r"\.genome_[Cc]hr([0-9]{1,2}[A-Za-z]{0,4})$")
_CHROM_ALT_RE = re.compile(r"[Cc]hr([0-9]{1,2}[A-Za-z]{0,4})$")

#: name -> normalised key ("Chr1A_AK58" -> "1a", "chr7A" -> "7a")
_NORM_STRIP_CHR = re.compile(r"^(chr|chromosome)", re.IGNORECASE)
_NORM_STRIP_SUFFIX = re.compile(r"_[a-z0-9.\-]+$", re.IGNORECASE)

_CACHE: dict = {"mtime": None, "map": {}}


def split_db_name(name: str) -> tuple[str, str, Optional[str]]:
    """Split a BLAST database name into (base, kind, chromosome).

    Mirrors ``_db_base_kind_chromosome`` in app/api/routers/blast.py (that
    module imports this service, so the helper is duplicated here on purpose
    to avoid a router -> service -> router import cycle). Keep both in sync.
    """
    name = (name or "").strip().rstrip("/")
    m = _CHROM_RE.search(name)
    if m:
        return name[: m.start()], "chromosome", m.group(1)
    m = _CHROM_ALT_RE.search(name)
    if m:
        return name[: m.start()], "chromosome", m.group(1)
    if name.startswith("all_"):
        return name, "aggregate", None
    for suffix, kind in ((".add_Description.cds", "cds"),
                         (".add_Description.pep", "protein")):
        if name.endswith(suffix):
            return name[: -len(suffix)], kind, None
    if name.endswith(".genome"):
        return name[: -len(".genome")], "genome", None
    if ".scaffold" in name:
        return re.sub(r"\.scaffold.*$", "", name) or name, "genome", None
    return name, "other", None


def normalize_token(token: str) -> str:
    """Normalised chromosome key: lower-case, drop ``chr`` prefix and the
    assembly suffix (``Chr1A_AK58`` / ``chr1A`` -> ``1a``)."""
    key = (token or "").strip().lower()
    key = _NORM_STRIP_CHR.sub("", key)
    key = _NORM_STRIP_SUFFIX.sub("", key)
    return key


def load_map() -> dict:
    """The generated mapping, reloaded when the file changes (never raises)."""
    try:
        mtime = os.path.getmtime(MAP_FILE)
    except OSError:
        return {}
    if _CACHE.get("mtime") != mtime:
        try:
            with open(MAP_FILE, encoding="utf-8") as fh:
                data = json.load(fh)
            _CACHE["map"] = data if isinstance(data, dict) else {}
        except (OSError, ValueError):
            _CACHE["map"] = {}
        _CACHE["mtime"] = mtime
    return _CACHE["map"]


def get_entry(db: str) -> tuple[dict, str, Optional[str]]:
    """Return (mapping entry, kind, chromosome) for a database name."""
    base, kind, chrom = split_db_name(db)
    data = load_map()
    entry = data.get(base) or data.get(db) or {}
    return entry, kind, chrom


def jbrowse_meta(db: str) -> dict:
    """Compact per-database browser info for ``/api/blast/databases``."""
    entry, kind, _chrom = get_entry(db)
    dataset = (entry or {}).get("dataset")
    if not dataset:
        return {"available": False, "reason": "no_jbrowse_dataset"}
    if kind in ("aggregate", "other"):
        return {"available": False, "reason": "aggregate_or_unknown_db", "dataset": dataset}
    if not entry.get("assembly_match"):
        return {
            "available": False,
            "reason": entry.get("reason") or "assembly_version_mismatch",
            "dataset": dataset,
        }
    if kind in ("cds", "protein") and not entry.get("annotation_ok"):
        return {"available": False, "reason": "annotation_coordinates_unknown", "dataset": dataset}
    if not (entry.get("chroms") or entry.get("norm")):
        return {"available": False, "reason": "no_refseq_mapping", "dataset": dataset}
    return {
        "available": True,
        "dataset": dataset,
        "browser": entry.get("browser") or "jbrowse1",
    }


def url_template(dataset: str) -> str:
    """JBrowse deep-link template; ``{loc}`` is replaced by refseq:start..end."""
    base = getattr(settings, "JBROWSE_WEB_PATH", "/jbrowse-1.12.3-release")
    return f"{base.rstrip('/')}/?data={urllib.parse.quote(dataset)}&loc={{loc}}"


def resolve_tokens(db: str, tokens: Iterable[str]) -> dict:
    """Resolve subject ids / chromosome tokens of one database to refseq names.

    Lookup order per token: exact seqid -> lower-case -> normalised key. Tokens
    that cannot be resolved are returned under ``unresolved`` so the caller can
    decide (the UI simply omits its button).
    """
    tokens = [str(t).strip() for t in tokens if str(t or "").strip()][:MAX_TOKENS]
    entry, kind, chrom = get_entry(db)
    info = jbrowse_meta(db)
    result = {
        "database": db,
        "base": split_db_name(db)[0],
        "kind": kind,
        "chromosome": chrom,
        "available": bool(info.get("available")),
        "reason": info.get("reason"),
        "dataset": info.get("dataset"),
        "browser": info.get("browser"),
        "template": url_template(info["dataset"]) if info.get("dataset") else None,
        "resolved": {},
        "unresolved": [],
    }
    if not result["available"]:
        result["unresolved"] = tokens
        return result

    chroms = entry.get("chroms") or {}
    norm = entry.get("norm") or {}
    for token in tokens:
        refseq = chroms.get(token) or chroms.get(token.lower())
        if not refseq:
            refseq = norm.get(normalize_token(token))
        if refseq:
            result["resolved"][token] = refseq
        else:
            result["unresolved"].append(token)
    return result
