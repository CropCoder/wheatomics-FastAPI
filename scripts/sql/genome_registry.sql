-- 基因组信息库：元数据 / 来源 / 网站各模块使用情况
-- 数据库：wheatomics_db（config: DB_LITERATURE）
-- 维护：scripts/rebuild_genome_registry.py（从平台事实重建，幂等 upsert）
-- 创建：2026-10-22
CREATE TABLE IF NOT EXISTS `wheatomics_db`.`genome_registry` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `dataset_id` varchar(160) NOT NULL COMMENT '平台主标识（PLOIDY_MYTAG 或 JBrowse 数据集 id）',
  `display_name` varchar(160) DEFAULT NULL COMMENT '展示名',
  `species` varchar(255) DEFAULT NULL,
  `ploidy` varchar(100) DEFAULT NULL COMMENT 'AABBDD/AABBRR/HH/SS 等',
  `subgenomes` varchar(64) DEFAULT NULL COMMENT 'A,B,D 等',
  `cultivar_or_line` varchar(255) DEFAULT NULL,
  `jbrowse_dataset` varchar(160) DEFAULT NULL COMMENT 'JBrowse ?data= 用的 id',
  `assembly_accession` varchar(160) DEFAULT NULL COMMENT 'GWH/NCBI 组装号',
  `assembly_version` varchar(64) DEFAULT NULL,
  `assembly_level` varchar(64) DEFAULT NULL,
  `assembly_date` date DEFAULT NULL,
  `genome_size` bigint(20) DEFAULT NULL,
  `chromosome_count` int(11) DEFAULT NULL,
  `source_url` varchar(600) DEFAULT NULL COMMENT '原始数据下载页',
  `source_file` varchar(600) DEFAULT NULL COMMENT '服务器原始文件路径',
  `source_md5` char(32) DEFAULT NULL,
  `doi` varchar(255) DEFAULT NULL COMMENT '论文 DOI',
  `paper_title` text,
  `annotation_status` enum('none','pending','available') NOT NULL DEFAULT 'none',
  `annotation_source` varchar(255) DEFAULT NULL,
  `annotation_doi` varchar(255) DEFAULT NULL,
  `gene_table` varchar(160) DEFAULT NULL COMMENT 'Genefunc_* 表',
  `blast_genome_db` varchar(160) DEFAULT NULL,
  `blast_cds_db` varchar(160) DEFAULT NULL,
  `blast_pep_db` varchar(160) DEFAULT NULL,
  `getfasta_member` tinyint(1) NOT NULL DEFAULT 0,
  `primerserver_fai` tinyint(1) NOT NULL DEFAULT 0,
  `web_blast_group` tinyint(1) NOT NULL DEFAULT 0,
  `gene_function_ui` tinyint(1) NOT NULL DEFAULT 0,
  `synteny_entry` tinyint(1) NOT NULL DEFAULT 0,
  `orthofinder_entry` tinyint(1) NOT NULL DEFAULT 0,
  `aliases_json` json DEFAULT NULL COMMENT '各模块中该基因组的名字',
  `usage_json` json DEFAULT NULL COMMENT '网站各模块使用证据（DB/路径/接口）',
  `notes` text,
  `visible` tinyint(1) NOT NULL DEFAULT 1,
  `created_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_dataset` (`dataset_id`),
  KEY `idx_ploidy` (`ploidy`),
  KEY `idx_annotation` (`annotation_status`),
  KEY `idx_jbrowse` (`jbrowse_dataset`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='基因组信息库：元数据/来源/网站使用情况';
